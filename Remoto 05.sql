## ESTAREMOS CRIANDO RELAÇÕES ENTRE VARIA TABELA

USE bd;
## CARDIONALIDADE  1:1, 1:N, N:N
## TABELA USUARIO
CREATE TABLE TB_USUARIO(
 id_us int auto_increment primary key, 
 nome_us varchar(100) not null ,
 email_us varchar(100)not null,
 senha_us varchar(20) not null
);

## TABELA PRODUTO

CREATE TABLE TB_PRODUTO(
 id_prod int primary key auto_increment,
 nome_prod varchar(100) not null,
 desc_prod text,
 valorUni_prod decimal(10,2) not null
 );

## TABELA DE RELACIONAMENTO N:N 

CREATE TABLE TB_USUARIO_PRODUTO(
 id_usprod int primary key auto_increment,
 id_us int not null,
 id_prod int not null,
 npedido_us varchar(10)  not  null,
 qtd_usprod int  not null,
 dataComp_usprod datetime  not null,
 constraint fk_usuario foreign key (id_us)  references TB_USUARIO(id_us),
constraint fk_produto foreign key (id_prod)  references TB_PRODUTO(id_prod)
);

